/// The junction current contains an already-rounded linear gmin term.
/// Subtract the same rounded product so pure linear conduction stamps
/// exactly zero equivalent current, not the rounding residual of gmin*v.
#[expect(
    clippy::suboptimal_flops,
    reason = "subtract the same rounded linear current generated by the junction, preserving exact zero equivalent current"
)]
fn junction_source(current: f64, slope: f64, voltage: f64) -> f64 {
    current - slope * voltage
}

/// Emit C line900 RHS and matrix contributions without coalescing or reordering.
pub(super) fn apply(
    model: &Model,
    here: &Instance,
    ckt: &mut dyn LoadCkt,
    bias: &LoadBias,
    cdrain: f64,
    companion: &Companion,
) {
    let &LoadBias {
        qdef,
        vbd,
        vbd_jct,
        vbs,
        vbs_jct,
        vds,
        vgd,
        vges,
        vgms,
        vgs,
        ..
    } = bias;
    let &Companion {
        currents:
            ChargeCurrents {
                mut ceqqb,
                mut ceqqd,
                mut ceqqg,
                mut ceqqgmid,
                mut ceqqjd,
                mut ceqqjs,
            },
        capacitance:
            CapacitanceStamp {
                gcbbb,
                gcbdb,
                gcbgb,
                gcbgmb,
                gcbsb,
                gcdbb,
                gcdbdb,
                gcddb,
                gcdgb,
                gcdgmb,
                gcdsb,
                gcgbb,
                gcgdb,
                gcggb,
                gcgmbb,
                gcgmdb,
                gcgmgmb,
                gcgmsb,
                gcgsb,
                gcsbb,
                gcsbsb,
                gcsdb,
                gcsgb,
                gcsgmb,
                gcssb,
            },
        nqs:
            NqsStamp {
                mut cqcheq,
                mut cqdef,
                ddxpart_dVb,
                ddxpart_dVd,
                ddxpart_dVg,
                ddxpart_dVs,
                dsxpart_dVb,
                dsxpart_dVd,
                dsxpart_dVg,
                dsxpart_dVs,
                dxpart,
                gcqbb,
                gcqdb,
                gcqgb,
                gcqsb,
                ggtb,
                ggtd,
                ggtg,
                ggts,
                gqdef,
                sxpart,
            },
    } = companion;
    let mut ceqgstot: f64;
    let mut ceqgdtot: f64;
    let mut gstot: f64;
    let mut gstotd: f64;
    let mut gstotg: f64;
    let mut gstots: f64;
    let mut gstotb: f64;
    let mut gspr: f64;
    let mut gdtot: f64;
    let mut gdtotd: f64;
    let mut gdtotg: f64;
    let mut gdtots: f64;
    let mut gdtotb: f64;
    let mut gdpr: f64;
    let mut geltd: f64;
    let mut gcrg: f64;
    let mut gcrgg: f64;
    let mut gcrgd: f64;
    let mut gcrgs: f64;
    let mut gcrgb: f64;
    let mut ceqgcrg: f64;
    let mut ceqdrn: f64;
    let mut ceqbd: f64;
    let mut ceqbs: f64;
    let mut ceqjd: f64;
    let mut ceqjs: f64;
    let mut gjbd: f64;
    let mut gjbs: f64;
    let mut Gmbs: f64;
    let mut FwdSum: f64;
    let mut RevSum: f64;
    let mut Istoteq: f64;
    let mut gIstotg: f64;
    let mut gIstotd: f64;
    let mut gIstots: f64;
    let mut gIstotb: f64;
    let mut Idtoteq: f64;
    let mut gIdtotg: f64;
    let mut gIdtotd: f64;
    let mut gIdtots: f64;
    let mut gIdtotb: f64;
    let mut Ibtoteq: f64;
    let mut gIbtotg: f64;
    let mut gIbtotd: f64;
    let mut gIbtots: f64;
    let mut gIbtotb: f64;
    let mut Igtoteq: f64;
    let mut gIgtotg: f64;
    let mut gIgtotd: f64;
    let mut gIgtots: f64;
    let mut gIgtotb: f64;
    let mut T1: f64;
    let mut Gm: f64;
    let mut gbspsp: f64;
    let mut gbbdp: f64;
    let mut gbbsp: f64;
    let mut gbspg: f64;
    let mut gbspb: f64;
    let mut gbspdp: f64;
    let mut gbdpdp: f64;
    let mut gbdpg: f64;
    let mut gbdpb: f64;
    let mut gbdpsp: f64;
    let mut m: f64;
    let mut mult_i: f64;
    let mut mult_q: f64;
    // C label `line900:`.
    if here.mode >= 0 {
        Gm = here.gm;
        Gmbs = here.gmbs;
        FwdSum = Gm + Gmbs;
        RevSum = 0.0;
        ceqdrn = f64::from(model.r#type)
            * Gmbs.mul_add(-vbs, Gm.mul_add(-vgs, here.gds.mul_add(-vds, cdrain)));
        ceqbd = f64::from(model.r#type)
            * (here.gbbs + here.ggidlb).mul_add(
                -vbs,
                (here.gbgs + here.ggidlg).mul_add(
                    -vgs,
                    (here.gbds + here.ggidld).mul_add(-vds, here.csub + here.Igidl),
                ),
            );
        ceqbs = f64::from(model.r#type)
            * here.ggislb.mul_add(
                -vbd,
                here.ggislg
                    .mul_add(-vgd, here.ggisls.mul_add(vds, here.Igisl)),
            );
        gbbdp = -(here.gbds);
        gbbsp = here.gbds + here.gbgs + here.gbbs;
        gbdpg = here.gbgs;
        gbdpdp = here.gbds;
        gbdpb = here.gbbs;
        gbdpsp = -(gbdpg + gbdpdp + gbdpb);
        gbspg = 0.0;
        gbspdp = 0.0;
        gbspb = 0.0;
        gbspsp = 0.0;
        if model.igcMod != 0 {
            gIstotg = here.gIgsg + here.gIgcsg;
            gIstotd = here.gIgcsd;
            gIstots = here.gIgss + here.gIgcss;
            gIstotb = here.gIgcsb;
            Istoteq = f64::from(model.r#type)
                * here.gIgcsb.mul_add(
                    -vbs,
                    here.gIgcsd
                        .mul_add(-vds, gIstotg.mul_add(-vgs, here.Igs + here.Igcs)),
                );
            gIdtotg = here.gIgdg + here.gIgcdg;
            gIdtotd = here.gIgdd + here.gIgcdd;
            gIdtots = here.gIgcds;
            gIdtotb = here.gIgcdb;
            Idtoteq = f64::from(model.r#type)
                * here.gIgcdb.mul_add(
                    -vbs,
                    here.gIgcdd.mul_add(
                        -vds,
                        here.gIgcdg
                            .mul_add(-vgs, here.gIgdg.mul_add(-vgd, here.Igd + here.Igcd)),
                    ),
                );
        } else {
            Istoteq = 0.0;
            gIstotb = Istoteq;
            gIstots = gIstotb;
            gIstotd = gIstots;
            gIstotg = gIstotd;
            Idtoteq = 0.0;
            gIdtotb = Idtoteq;
            gIdtots = gIdtotb;
            gIdtotd = gIdtots;
            gIdtotg = gIdtotd;
        }
        if model.igbMod != 0 {
            gIbtotg = here.gIgbg;
            gIbtotd = here.gIgbd;
            gIbtots = here.gIgbs;
            gIbtotb = here.gIgbb;
            Ibtoteq = f64::from(model.r#type)
                * here.gIgbb.mul_add(
                    -vbs,
                    here.gIgbd.mul_add(-vds, here.gIgbg.mul_add(-vgs, here.Igb)),
                );
        } else {
            Ibtoteq = 0.0;
            gIbtotb = Ibtoteq;
            gIbtots = gIbtotb;
            gIbtotd = gIbtots;
            gIbtotg = gIbtotd;
        }
        if (model.igcMod != 0) || (model.igbMod != 0) {
            gIgtotg = gIstotg + gIdtotg + gIbtotg;
            gIgtotd = gIstotd + gIdtotd + gIbtotd;
            gIgtots = gIstots + gIdtots + gIbtots;
            gIgtotb = gIstotb + gIdtotb + gIbtotb;
            Igtoteq = Istoteq + Idtoteq + Ibtoteq;
        } else {
            Igtoteq = 0.0;
            gIgtotb = Igtoteq;
            gIgtots = gIgtotb;
            gIgtotd = gIgtots;
            gIgtotg = gIgtotd;
        }
        // Setup guarantees rgateMod is 0..=3; only 2/3 need a gate drop.
        if matches!(here.rgateMod, 2 | 3) {
            let T0 = if here.rgateMod == 2 {
                vges - vgs
            } else {
                vgms - vgs
            };
            gcrgd = here.gcrgd * T0;
            gcrgg = here.gcrgg * T0;
            gcrgs = here.gcrgs * T0;
            gcrgb = here.gcrgb * T0;
            ceqgcrg = -gcrgb.mul_add(vbs, gcrgg.mul_add(vgs, gcrgd * vds));
            gcrgg -= here.gcrg;
            gcrg = here.gcrg;
        } else {
            gcrgb = 0.0;
            gcrgs = gcrgb;
            gcrgg = gcrgs;
            gcrgd = gcrgg;
            gcrg = gcrgd;
            ceqgcrg = gcrg;
        }
    } else {
        Gm = -here.gm;
        Gmbs = -here.gmbs;
        FwdSum = 0.0;
        RevSum = -(Gm + Gmbs);
        ceqdrn = f64::from(-model.r#type)
            * Gmbs.mul_add(vbd, Gm.mul_add(vgd, here.gds.mul_add(vds, cdrain)));
        ceqbs = f64::from(model.r#type)
            * (here.gbbs + here.ggislb).mul_add(
                -vbd,
                (here.gbgs + here.ggislg).mul_add(
                    -vgd,
                    (here.gbds + here.ggisls).mul_add(vds, here.csub + here.Igisl),
                ),
            );
        ceqbd = f64::from(model.r#type)
            * here.ggidlb.mul_add(
                -vbs,
                here.ggidlg
                    .mul_add(-vgs, here.ggidld.mul_add(-vds, here.Igidl)),
            );
        gbbsp = -(here.gbds);
        gbbdp = here.gbds + here.gbgs + here.gbbs;
        gbdpg = 0.0;
        gbdpsp = 0.0;
        gbdpb = 0.0;
        gbdpdp = 0.0;
        gbspg = here.gbgs;
        gbspsp = here.gbds;
        gbspb = here.gbbs;
        gbspdp = -(gbspg + gbspsp + gbspb);
        if model.igcMod != 0 {
            gIstotg = here.gIgsg + here.gIgcdg;
            gIstotd = here.gIgcds;
            gIstots = here.gIgss + here.gIgcdd;
            gIstotb = here.gIgcdb;
            Istoteq = f64::from(model.r#type)
                * here.gIgcdb.mul_add(
                    -vbd,
                    here.gIgcdd.mul_add(
                        vds,
                        here.gIgcdg
                            .mul_add(-vgd, here.gIgsg.mul_add(-vgs, here.Igs + here.Igcd)),
                    ),
                );
            gIdtotg = here.gIgdg + here.gIgcsg;
            gIdtotd = here.gIgdd + here.gIgcss;
            gIdtots = here.gIgcsd;
            gIdtotb = here.gIgcsb;
            Idtoteq = f64::from(model.r#type)
                * here.gIgcsb.mul_add(
                    -vbd,
                    here.gIgcsd.mul_add(
                        vds,
                        (here.gIgdg + here.gIgcsg).mul_add(-vgd, here.Igd + here.Igcs),
                    ),
                );
        } else {
            Istoteq = 0.0;
            gIstotb = Istoteq;
            gIstots = gIstotb;
            gIstotd = gIstots;
            gIstotg = gIstotd;
            Idtoteq = 0.0;
            gIdtotb = Idtoteq;
            gIdtots = gIdtotb;
            gIdtotd = gIdtots;
            gIdtotg = gIdtotd;
        }
        if model.igbMod != 0 {
            gIbtotg = here.gIgbg;
            gIbtotd = here.gIgbs;
            gIbtots = here.gIgbd;
            gIbtotb = here.gIgbb;
            Ibtoteq = f64::from(model.r#type)
                * here.gIgbb.mul_add(
                    -vbd,
                    here.gIgbd.mul_add(vds, here.gIgbg.mul_add(-vgd, here.Igb)),
                );
        } else {
            Ibtoteq = 0.0;
            gIbtotb = Ibtoteq;
            gIbtots = gIbtotb;
            gIbtotd = gIbtots;
            gIbtotg = gIbtotd;
        }
        if (model.igcMod != 0) || (model.igbMod != 0) {
            gIgtotg = gIstotg + gIdtotg + gIbtotg;
            gIgtotd = gIstotd + gIdtotd + gIbtotd;
            gIgtots = gIstots + gIdtots + gIbtots;
            gIgtotb = gIstotb + gIdtotb + gIbtotb;
            Igtoteq = Istoteq + Idtoteq + Ibtoteq;
        } else {
            Igtoteq = 0.0;
            gIgtotb = Igtoteq;
            gIgtots = gIgtotb;
            gIgtotd = gIgtots;
            gIgtotg = gIgtotd;
        }
        // Setup guarantees rgateMod is 0..=3; only 2/3 need a gate drop.
        if matches!(here.rgateMod, 2 | 3) {
            let T0 = if here.rgateMod == 2 {
                vges - vgs
            } else {
                vgms - vgs
            };
            gcrgd = here.gcrgs * T0;
            gcrgg = here.gcrgg * T0;
            gcrgs = here.gcrgd * T0;
            gcrgb = here.gcrgb * T0;
            ceqgcrg = -gcrgb.mul_add(vbd, gcrgs.mul_add(-vds, gcrgg * vgd));
            gcrgg -= here.gcrg;
            gcrg = here.gcrg;
        } else {
            gcrgb = 0.0;
            gcrgs = gcrgb;
            gcrgg = gcrgs;
            gcrgd = gcrgg;
            gcrg = gcrgd;
            ceqgcrg = gcrg;
        }
    }
    if model.rdsMod == 1 {
        ceqgstot = f64::from(model.r#type)
            * here
                .gstotb
                .mul_add(vbs, here.gstotg.mul_add(vgs, here.gstotd * vds));
        gstot = here.gstot;
        gstotd = here.gstotd;
        gstotg = here.gstotg;
        gstots = here.gstots - gstot;
        gstotb = here.gstotb;
        ceqgdtot = f64::from(-model.r#type)
            * here
                .gdtotb
                .mul_add(vbs, here.gdtotg.mul_add(vgs, here.gdtotd * vds));
        gdtot = here.gdtot;
        gdtotd = here.gdtotd - gdtot;
        gdtotg = here.gdtotg;
        gdtots = here.gdtots;
        gdtotb = here.gdtotb;
    } else {
        ceqgstot = 0.0;
        gstotb = ceqgstot;
        gstots = gstotb;
        gstotg = gstots;
        gstotd = gstotg;
        gstot = gstotd;
        ceqgdtot = 0.0;
        gdtotb = ceqgdtot;
        gdtots = gdtotb;
        gdtotg = gdtots;
        gdtotd = gdtotg;
        gdtot = gdtotd;
    }
    if model.r#type > 0 {
        ceqjs = junction_source(here.cbs, here.gbs, vbs_jct);
        ceqjd = junction_source(here.cbd, here.gbd, vbd_jct);
    } else {
        ceqjs = -junction_source(here.cbs, here.gbs, vbs_jct);
        ceqjd = -junction_source(here.cbd, here.gbd, vbd_jct);
        ceqqg = -ceqqg;
        ceqqd = -ceqqd;
        ceqqb = -ceqqb;
        ceqgcrg = -ceqgcrg;
        if here.trnqsMod != 0 {
            cqdef = -cqdef;
            cqcheq = -cqcheq;
        }
        if here.rbodyMod != 0 {
            ceqqjs = -ceqqjs;
            ceqqjd = -ceqqjd;
        }
        if here.rgateMod == 3 {
            ceqqgmid = -ceqqgmid;
        }
    }
    m = here.m;
    mult_i = here.mult_i * here.m;
    mult_q = here.mult_q * here.m;
    ckt.rhs(
        here.dNodePrime,
        mult_q.mul_add(
            -ceqqd,
            mult_i * (ceqjd - ceqbd + ceqgdtot - ceqdrn + Idtoteq),
        ),
    );
    ckt.rhs(
        here.gNodePrime,
        -mult_i.mul_add(-(ceqgcrg - Igtoteq), mult_q * ceqqg),
    );
    if here.rgateMod == 2 {
        ckt.rhs(here.gNodeExt, -(mult_i * ceqgcrg));
    } else if here.rgateMod == 3 {
        ckt.rhs(here.gNodeMid, -mult_i.mul_add(ceqgcrg, mult_q * ceqqgmid));
    }
    if here.rbodyMod == 0 {
        ckt.rhs(
            here.bNodePrime,
            mult_q.mul_add(-ceqqb, mult_i * (ceqbd + ceqbs - ceqjd - ceqjs + Ibtoteq)),
        );
        ckt.rhs(
            here.sNodePrime,
            mult_q.mul_add(
                ceqqg + ceqqb + ceqqd + ceqqgmid,
                mult_i * (ceqdrn - ceqbs + ceqjs - ceqgstot + Istoteq),
            ),
        );
    } else {
        ckt.rhs(here.dbNode, -mult_q.mul_add(ceqqjd, mult_i * (ceqjd)));
        ckt.rhs(
            here.bNodePrime,
            mult_q.mul_add(-ceqqb, mult_i * (ceqbd + ceqbs + Ibtoteq)),
        );
        ckt.rhs(here.sbNode, -mult_q.mul_add(ceqqjs, mult_i * (ceqjs)));
        ckt.rhs(
            here.sNodePrime,
            mult_q.mul_add(
                ceqqd + ceqqg + ceqqb + ceqqjd + ceqqjs + ceqqgmid,
                mult_i * (ceqdrn - ceqbs + ceqjs - ceqgstot + Istoteq),
            ),
        );
    }
    if model.rdsMod != 0 {
        ckt.rhs(here.dNode, -(mult_i * ceqgdtot));
        ckt.rhs(here.sNode, mult_i * ceqgstot);
    }
    if here.trnqsMod != 0 {
        ckt.rhs(here.qNode, m * (cqcheq - cqdef));
    }
    if here.rbodyMod == 0 {
        gjbd = here.gbd;
        gjbs = here.gbs;
    } else {
        gjbs = 0.0;
        gjbd = gjbs;
    }
    if model.rdsMod == 0 {
        gdpr = here.drainConductance;
        gspr = here.sourceConductance;
    } else {
        gspr = 0.0;
        gdpr = gspr;
    }
    geltd = here.grgeltd;
    T1 = qdef * here.gtau;
    if here.rgateMod == 1 {
        ckt.matrix(here.gNodeExt, here.gNodeExt, mult_i * geltd);
        ckt.matrix(here.gNodePrime, here.gNodeExt, -(mult_i * geltd));
        ckt.matrix(here.gNodeExt, here.gNodePrime, -(mult_i * geltd));
        ckt.matrix(
            here.gNodePrime,
            here.gNodePrime,
            mult_i.mul_add(geltd + gIgtotg, mult_q * (gcggb - ggtg)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.dNodePrime,
            mult_i.mul_add(gIgtotd, mult_q * (gcgdb - ggtd)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.sNodePrime,
            mult_i.mul_add(gIgtots, mult_q * (gcgsb - ggts)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.bNodePrime,
            mult_i.mul_add(gIgtotb, mult_q * (gcgbb - ggtb)),
        );
    } else if here.rgateMod == 2 {
        ckt.matrix(here.gNodeExt, here.gNodeExt, mult_i * gcrg);
        ckt.matrix(here.gNodeExt, here.gNodePrime, mult_i * gcrgg);
        ckt.matrix(here.gNodeExt, here.dNodePrime, mult_i * gcrgd);
        ckt.matrix(here.gNodeExt, here.sNodePrime, mult_i * gcrgs);
        ckt.matrix(here.gNodeExt, here.bNodePrime, mult_i * gcrgb);
        ckt.matrix(here.gNodePrime, here.gNodeExt, -(mult_i * gcrg));
        ckt.matrix(
            here.gNodePrime,
            here.gNodePrime,
            mult_i.mul_add(gIgtotg - gcrgg, mult_q * (gcggb - ggtg)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.dNodePrime,
            mult_i.mul_add(gIgtotd - gcrgd, mult_q * (gcgdb - ggtd)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.sNodePrime,
            mult_i.mul_add(gIgtots - gcrgs, mult_q * (gcgsb - ggts)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.bNodePrime,
            mult_i.mul_add(gIgtotb - gcrgb, mult_q * (gcgbb - ggtb)),
        );
    } else if here.rgateMod == 3 {
        ckt.matrix(here.gNodeExt, here.gNodeExt, mult_i * geltd);
        ckt.matrix(here.gNodeExt, here.gNodeMid, -(mult_i * geltd));
        ckt.matrix(here.gNodeMid, here.gNodeExt, -(mult_i * geltd));
        ckt.matrix(
            here.gNodeMid,
            here.gNodeMid,
            mult_q.mul_add(gcgmgmb, mult_i * (geltd + gcrg)),
        );
        ckt.matrix(
            here.gNodeMid,
            here.dNodePrime,
            mult_q.mul_add(gcgmdb, mult_i * gcrgd),
        );
        ckt.matrix(here.gNodeMid, here.gNodePrime, mult_i * gcrgg);
        ckt.matrix(
            here.gNodeMid,
            here.sNodePrime,
            mult_q.mul_add(gcgmsb, mult_i * gcrgs),
        );
        ckt.matrix(
            here.gNodeMid,
            here.bNodePrime,
            mult_q.mul_add(gcgmbb, mult_i * gcrgb),
        );
        ckt.matrix(here.dNodePrime, here.gNodeMid, mult_q * gcdgmb);
        ckt.matrix(here.gNodePrime, here.gNodeMid, -(mult_i * gcrg));
        ckt.matrix(here.sNodePrime, here.gNodeMid, mult_q * gcsgmb);
        ckt.matrix(here.bNodePrime, here.gNodeMid, mult_q * gcbgmb);
        ckt.matrix(
            here.gNodePrime,
            here.gNodePrime,
            mult_i.mul_add(gIgtotg - gcrgg, mult_q * (gcggb - ggtg)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.dNodePrime,
            mult_i.mul_add(gIgtotd - gcrgd, mult_q * (gcgdb - ggtd)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.sNodePrime,
            mult_i.mul_add(gIgtots - gcrgs, mult_q * (gcgsb - ggts)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.bNodePrime,
            mult_i.mul_add(gIgtotb - gcrgb, mult_q * (gcgbb - ggtb)),
        );
    } else {
        ckt.matrix(
            here.gNodePrime,
            here.gNodePrime,
            mult_i.mul_add(gIgtotg, mult_q * (gcggb - ggtg)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.dNodePrime,
            mult_i.mul_add(gIgtotd, mult_q * (gcgdb - ggtd)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.sNodePrime,
            mult_i.mul_add(gIgtots, mult_q * (gcgsb - ggts)),
        );
        ckt.matrix(
            here.gNodePrime,
            here.bNodePrime,
            mult_i.mul_add(gIgtotb, mult_q * (gcgbb - ggtb)),
        );
    }
    if model.rdsMod != 0 {
        ckt.matrix(here.dNode, here.gNodePrime, mult_i * gdtotg);
        ckt.matrix(here.dNode, here.sNodePrime, mult_i * gdtots);
        ckt.matrix(here.dNode, here.bNodePrime, mult_i * gdtotb);
        ckt.matrix(here.sNode, here.dNodePrime, mult_i * gstotd);
        ckt.matrix(here.sNode, here.gNodePrime, mult_i * gstotg);
        ckt.matrix(here.sNode, here.bNodePrime, mult_i * gstotb);
    }
    ckt.matrix(
        here.dNodePrime,
        here.dNodePrime,
        mult_q.mul_add(
            dxpart.mul_add(ggtd, T1.mul_add(ddxpart_dVd, gcddb)),
            mult_i * (gdpr + here.gds + here.gbd - gdtotd + RevSum + gbdpdp - gIdtotd),
        ),
    );
    ckt.matrix(here.dNodePrime, here.dNode, -(mult_i * (gdpr + gdtot)));
    ckt.matrix(
        here.dNodePrime,
        here.gNodePrime,
        mult_q.mul_add(
            T1.mul_add(ddxpart_dVg, dxpart * ggtg) + gcdgb,
            mult_i * (Gm - gdtotg + gbdpg - gIdtotg),
        ),
    );
    ckt.matrix(
        here.dNodePrime,
        here.sNodePrime,
        -mult_q.mul_add(
            -(T1.mul_add(ddxpart_dVs, dxpart * ggts) + gcdsb),
            mult_i * (here.gds + gdtots + gIdtots + FwdSum - gbdpsp),
        ),
    );
    ckt.matrix(
        here.dNodePrime,
        here.bNodePrime,
        -mult_q.mul_add(
            -T1.mul_add(ddxpart_dVb, f64::mul_add(dxpart, ggtb, gcdbb)),
            mult_i * (gjbd + gdtotb - Gmbs - gbdpb + gIdtotb),
        ),
    );
    ckt.matrix(here.dNode, here.dNodePrime, -(mult_i * (gdpr - gdtotd)));
    ckt.matrix(here.dNode, here.dNode, mult_i * (gdpr + gdtot));
    ckt.matrix(
        here.sNodePrime,
        here.dNodePrime,
        -mult_q.mul_add(
            -(f64::mul_add(sxpart, ggtd, T1 * dsxpart_dVd) + gcsdb),
            mult_i * (here.gds + gstotd + RevSum - gbspdp + gIstotd),
        ),
    );
    ckt.matrix(
        here.sNodePrime,
        here.gNodePrime,
        mult_i.mul_add(
            gbspg - Gm - gstotg - gIstotg,
            mult_q * T1.mul_add(dsxpart_dVg, f64::mul_add(sxpart, ggtg, gcsgb)),
        ),
    );
    ckt.matrix(
        here.sNodePrime,
        here.sNodePrime,
        mult_q.mul_add(
            T1.mul_add(dsxpart_dVs, sxpart * ggts) + gcssb,
            mult_i * (gspr + here.gds + here.gbs - gIstots - gstots + FwdSum + gbspsp),
        ),
    );
    ckt.matrix(here.sNodePrime, here.sNode, -(mult_i * (gspr + gstot)));
    ckt.matrix(
        here.sNodePrime,
        here.bNodePrime,
        -mult_q.mul_add(
            -T1.mul_add(dsxpart_dVb, f64::mul_add(sxpart, ggtb, gcsbb)),
            mult_i * (gjbs + gstotb + Gmbs - gbspb + gIstotb),
        ),
    );
    ckt.matrix(here.sNode, here.sNodePrime, -(mult_i * (gspr - gstots)));
    ckt.matrix(here.sNode, here.sNode, mult_i * (gspr + gstot));
    ckt.matrix(
        here.bNodePrime,
        here.dNodePrime,
        mult_i.mul_add(-(gjbd - gbbdp + gIbtotd), mult_q * gcbdb),
    );
    ckt.matrix(
        here.bNodePrime,
        here.gNodePrime,
        mult_i.mul_add(-(here.gbgs + gIbtotg), mult_q * gcbgb),
    );
    ckt.matrix(
        here.bNodePrime,
        here.sNodePrime,
        mult_i.mul_add(-(gjbs - gbbsp + gIbtots), mult_q * gcbsb),
    );
    ckt.matrix(
        here.bNodePrime,
        here.bNodePrime,
        mult_q.mul_add(gcbbb, mult_i * (gjbd + gjbs - here.gbbs - gIbtotb)),
    );
    super::super::stamp_common::leakage(here, mult_i, |row, col, value| {
        ckt.matrix(row, col, value);
    });
    if here.rbodyMod != 0 {
        ckt.matrix(
            here.dNodePrime,
            here.dbNode,
            mult_i.mul_add(-here.gbd, mult_q * gcdbdb),
        );
        ckt.matrix(
            here.sNodePrime,
            here.sbNode,
            -mult_q.mul_add(-gcsbsb, mult_i * here.gbs),
        );
        ckt.matrix(
            here.dbNode,
            here.dNodePrime,
            mult_i.mul_add(-here.gbd, mult_q * gcdbdb),
        );
        ckt.matrix(
            here.dbNode,
            here.dbNode,
            mult_q.mul_add(-gcdbdb, mult_i * (here.gbd + here.grbpd + here.grbdb)),
        );
        ckt.matrix(here.dbNode, here.bNodePrime, -(mult_i * here.grbpd));
        ckt.matrix(here.dbNode, here.bNode, -(mult_i * here.grbdb));
        ckt.matrix(here.bNodePrime, here.dbNode, -(mult_i * here.grbpd));
        ckt.matrix(here.bNodePrime, here.bNode, -(mult_i * here.grbpb));
        ckt.matrix(here.bNodePrime, here.sbNode, -(mult_i * here.grbps));
        ckt.matrix(
            here.bNodePrime,
            here.bNodePrime,
            mult_i * (here.grbpd + here.grbps + here.grbpb),
        );
        ckt.matrix(
            here.sbNode,
            here.sNodePrime,
            mult_i.mul_add(-here.gbs, mult_q * gcsbsb),
        );
        ckt.matrix(here.sbNode, here.bNodePrime, -(mult_i * here.grbps));
        ckt.matrix(here.sbNode, here.bNode, -(mult_i * here.grbsb));
        ckt.matrix(
            here.sbNode,
            here.sbNode,
            mult_q.mul_add(-gcsbsb, mult_i * (here.gbs + here.grbps + here.grbsb)),
        );
        ckt.matrix(here.bNode, here.dbNode, -(mult_i * here.grbdb));
        ckt.matrix(here.bNode, here.bNodePrime, -(mult_i * here.grbpb));
        ckt.matrix(here.bNode, here.sbNode, -(mult_i * here.grbsb));
        ckt.matrix(
            here.bNode,
            here.bNode,
            mult_i * (here.grbsb + here.grbdb + here.grbpb),
        );
    }
    if here.trnqsMod != 0 {
        ckt.matrix(here.qNode, here.qNode, m * (gqdef + here.gtau));
        ckt.matrix(here.qNode, here.gNodePrime, m * (ggtg - gcqgb));
        ckt.matrix(here.qNode, here.dNodePrime, m * (ggtd - gcqdb));
        ckt.matrix(here.qNode, here.sNodePrime, m * (ggts - gcqsb));
        ckt.matrix(here.qNode, here.bNodePrime, m * (ggtb - gcqbb));
        ckt.matrix(here.dNodePrime, here.qNode, mult_q * (dxpart * here.gtau));
        ckt.matrix(here.sNodePrime, here.qNode, mult_q * (sxpart * here.gtau));
        ckt.matrix(here.gNodePrime, here.qNode, -(mult_q * (here.gtau)));
    }
}

