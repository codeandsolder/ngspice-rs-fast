//! End-to-end LTspice source lowering and native solver phase qualification.
use std::sync::Arc;

use anyhow::{Context, Result, ensure};
use ngspice_rs::{
    analysis::{AnalysisInput, Plot, RunConfig},
    devices::subckt::PreparedDeclarations,
    netlist::Parser,
    primitives::AnalysisKind,
};
use ngspice_rs_preprocess::{Cancellation, InputFormat, Options, Request, SourceInput, prepare};

fn run_source(source: &str, kind: AnalysisKind, arguments: &[&str]) -> Result<Plot> {
    let dir = tempfile::tempdir()?;
    let bundle = prepare(
        &Request {
            format: InputFormat::LtspiceDeck,
            input: SourceInput::Bytes {
                origin: dir.path().join("source.cir"),
                bytes: Arc::from(source.as_bytes()),
            },
            libraries: Vec::new(),
            search_paths: Vec::new(),
        },
        &Options::default(),
        &Cancellation::default(),
    )?;
    for artifact in bundle.artifacts() {
        std::fs::write(dir.path().join(&artifact.filename), &artifact.bytes)?;
    }
    let deck = Parser::new().parse_file(dir.path().join(&bundle.primary.filename))?;
    let config = RunConfig::from_netlist(&deck)?;
    let mut circuit = config.prepared_circuit(
        &deck,
        PreparedDeclarations {
            waveforms: &bundle.waveforms,
            pwl_resistors: &bundle.pwl_resistors,
        },
    )?;
    Ok(config
        .plan(AnalysisInput::with_arguments(
            kind,
            arguments.iter().copied(),
        ))?
        .run(&mut circuit, &config.context())?)
}

fn value(plot: &Plot, name: &str, point: usize) -> Result<f64> {
    Ok(plot
        .value(name, point)
        .with_context(|| format!("missing {name} at point {point}"))?
        .re)
}

fn close(actual: f64, expected: f64, name: &str, point: usize) -> Result<()> {
    ensure!(
        (actual - expected).abs() <= 1e-9 * expected.abs().max(1.),
        "{name} at {point}: {actual:.17e} != {expected:.17e}"
    );
    Ok(())
}

#[test]
fn source_projection_matches_independent_vendor_scalar_sweep() -> Result<()> {
    // The circuit and data are the independent witnesses published with
    // producer #48, not outputs generated by either Rust implementation.
    let source = include_str!("fixtures/ltspice_scalar/scalar-dc.cir");
    let plot = run_source(source, AnalysisKind::DcSweep, &["Vx", "-3", "3", ".25"])?;
    let names = [
        "v(x)", "v(a)", "v(b)", "v(c)", "v(d)", "v(e)", "v(f)", "v(g)", "v(h)", "v(j)", "v(k)",
        "v(l)", "v(m)", "v(n)", "v(p)", "v(q)", "v(r)", "v(s)", "v(t)", "v(u)", "v(w)",
    ];
    let rows = include_str!("fixtures/ltspice_scalar/scalar-dc.tsv");
    ensure!(plot.point_count() == rows.lines().count());
    for (point, row) in rows.lines().enumerate() {
        let data = row
            .split_ascii_whitespace()
            .map(str::parse::<f64>)
            .collect::<Result<Vec<_>, _>>()?;
        ensure!(data.len() == names.len() + 1);
        for (index, (&name, &expected)) in names.iter().zip(&data[1..]).enumerate() {
            let actual = value(&plot, name, point)?;
            if (data[0] - 0.5).abs() <= f64::EPSILON && (4..9).contains(&index) {
                // Both native solvers can evaluate one ULP on either side
                // of a discontinuity during Newton iteration. The exact
                // static threshold is tested separately below.
                ensure!(actual.abs() < 1e-9 || (actual - 1.).abs() < 1e-9);
            } else {
                close(actual, expected, name, point)?;
            }
        }
        let x = value(&plot, "v(x)", point)?;
        close(x, data[0], "sweep", point)?;
    }
    Ok(())
}

const PHASE_SOURCE: &str = "\
LTspice phase witnesses
.options reltol=1e-10 abstol=1e-14 vntol=1e-12
.func tab(x) {table(x,-1,2,0,5,2,1)}
.func choose(x) {if(x,tab(x),limit(x,2,-2))}
.func outer(x) {choose(x)}
.param static={outer(0.5)}
.param knot={tab(1)}
Vstatic s 0 {static}
Vknot k 0 {knot}
B1 a 0 V=outer(V(x))
B2 b 0 V=uplim(V(x),1,.5)
B3 c 0 V=dnlim(V(x),-1,.5)
B4 d 0 V=tab(V(x))
R1 a 0 1k
R2 b 0 1k
R3 c 0 1k
R4 d 0 1k
";

#[test]
fn source_nested_macros_preserve_static_values_and_runtime_derivatives() -> Result<()> {
    let source = format!("{PHASE_SOURCE}Vx x 0 DC .75 AC 1\n.end\n");
    let op = run_source(&source, AnalysisKind::OperatingPoint, &[])?;
    for (name, expected) in [
        ("v(s)", 0.5),
        ("v(k)", 3.),
        ("v(a)", 3.5),
        ("v(d)", 3.5),
        ("v(b)", 0.5_f64.mul_add(-(-0.5_f64).exp(), 1.)),
        ("v(c)", 0.75),
    ] {
        close(value(&op, name, 0)?, expected, name, 0)?;
    }
    let ac = run_source(&source, AnalysisKind::Ac, &["lin", "3", "1k", "10k"])?;
    ensure!(ac.point_count() == 3);
    for point in 0..ac.point_count() {
        for (name, expected) in [
            ("v(s)", 0.),
            ("v(k)", 0.),
            ("v(a)", -2.),
            ("v(d)", -2.),
            ("v(b)", (-0.5_f64).exp()),
            ("v(c)", 1.),
        ] {
            let sample = ac
                .value(name, point)
                .with_context(|| format!("missing {name}"))?;
            close(sample.re, expected, name, point)?;
            close(sample.im, 0., name, point)?;
        }
    }
    Ok(())
}

#[test]
fn source_nested_macros_follow_the_transient_input() -> Result<()> {
    let source = format!("{PHASE_SOURCE}Vx x 0 PWL(0 .6 1m .9)\n.end\n");
    let tran = run_source(&source, AnalysisKind::Transient, &["10u", "1m"])?;
    ensure!(tran.point_count() > 50);
    for point in 0..tran.point_count() {
        let time = value(&tran, "time", point)?;
        let x = 300_f64.mul_add(time, 0.6);
        for (name, expected) in [
            ("v(s)", 0.5),
            ("v(k)", 3.),
            ("v(x)", x),
            ("v(a)", (-2_f64).mul_add(x, 5.)),
            ("v(d)", (-2_f64).mul_add(x, 5.)),
            ("v(b)", 0.5_f64.mul_add(-((0.5 - x) / 0.5).exp(), 1.)),
            ("v(c)", x),
        ] {
            close(value(&tran, name, point)?, expected, name, point)?;
        }
    }
    Ok(())
}
