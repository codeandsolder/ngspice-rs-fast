#!/usr/bin/env bash
# Emit an executable-specific set of functions from the real SPICE elaborator.
set -euo pipefail
if [[ $# != 1 ]]; then echo "usage: $0 /path/to/circuit_lto" >&2; exit 2; fi
binary=$1
root=$(git rev-parse --show-toplevel)
cd "$root"
out=src/devices/circuit/specialization/generated.rs
tmp="$out.tmp"
trap 'rm -f "$tmp"' EXIT
{
  echo '//! @generated by experiments/circuit-lto/generate.sh'
  echo '#![allow(clippy::too_many_arguments, clippy::too_many_lines, reason = "generated circuit specialization")]'
  echo 'use super::*;'
  for case in 0 1 2 3 4; do
    "$binary" emit "$case"
  done
  cat <<'RUST'
pub(in crate::devices::circuit) fn matches(case: usize, circuit: &Circuit, model: &ModelContext) -> SpiceResult<bool> {
    match case {
        0 => check_0(circuit, model),
        1 => check_1(circuit, model),
        2 => check_2(circuit, model),
        3 => check_3(circuit, model),
        4 => check_4(circuit, model),
        _ => Ok(false),
    }
}
pub(in crate::devices::circuit) fn dispatch(case: usize, bake: bool, circuit: &Circuit, request: &LoadRequest<'_>, matrix: &mut SparseMatrix, rhs: &mut Vector, trial: &mut TrialState, mutual: &[Vec<MutualTerm>], voltage_source_value: &mut Real) -> SpiceResult<bool> {
    // Circuit temperatures are part of the specialization key. Dynamic
    // temperature and device overrides must retain the generic execution path.
    if request.model_context.temperature.to_bits() != 27.0f64.to_bits()
        || request.model_context.nominal_temperature.to_bits() != 27.0f64.to_bits() {
        return Ok(false);
    }
    macro_rules! run {
        ($function:ident) => {
            if bake {
                $function::<true>(circuit, request, matrix, rhs, trial, mutual, voltage_source_value)?
            } else {
                $function::<false>(circuit, request, matrix, rhs, trial, mutual, voltage_source_value)?
            }
        }
    }
    match case {
        0 => run!(case_0),
        1 => run!(case_1),
        2 => run!(case_2),
        3 => run!(case_3),
        4 => run!(case_4),
        _ => return Ok(false),
    }
    Ok(true)
}
RUST
} > "$tmp"
mv "$tmp" "$out"
